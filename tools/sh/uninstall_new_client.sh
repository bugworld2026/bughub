#!/bin/bash
# ============================================================================
# UNINSTALL NEW CLIENT (Hard Eject)
# Mandate: Removes USoT config, Bugbase, and materialized paths.
# Location: C:\dbug\workspace\bughub-installer\tools\sh\uninstall_new_client.sh
# ============================================================================
set -euo pipefail

WORKSPACE_ROOT="C:/dbug/workspace"
CONFIG_PATH="$WORKSPACE_ROOT/config.json"

echo "=== BUGWORLD CLIENT UNINSTALLER ==="

# --- 1. Read USoT Config ---
if [[ ! -f "$CONFIG_PATH" ]]; then
    echo "WARN: USoT config not found. Nothing to uninstall."
    exit 0
fi

# Extract GUID and ENV using simple grep/sed (or jq if available)
# Assuming standard JSON format generated by installer
GUID=$(grep -o '"GUID": "[^"]*"' "$CONFIG_PATH" | cut -d'"' -f4)
ENV=$(grep -o '"ENV": "[^"]*"' "$CONFIG_PATH" | cut -d'"' -f4)

if [[ -z "$GUID" || -z "$ENV" ]]; then
    echo "FATAL: Could not parse GUID/ENV from config."
    exit 1
fi

echo "Uninstalling client for GUID: $GUID, ENV: $ENV"

# --- 2. Eject Cassette & Remove Bugbase ---
BUGBASE_PATH="$WORKSPACE_ROOT/sessions/$GUID/$ENV/config/bugbase.db"
if [[ -f "$BUGBASE_PATH" ]]; then
    echo "Removing Bugbase: $BUGBASE_PATH"
    rm -f "$BUGBASE_PATH"
fi

# --- 3. Remove Materialized Paths (Superid PTS) ---
CHAR_EXPANSION=$(echo "$GUID" | sed 's/./&\\/g' | sed 's/\\$//')
SUPERID_PTS_PATH="C:/dbug/superid/$GUID/$ENV/$CHAR_EXPANSION"

if [[ -d "$SUPERID_PTS_PATH" ]]; then
    echo "Removing Superid PTS stub: $SUPERID_PTS_PATH"
    rm -rf "$SUPERID_PTS_PATH"
fi

# --- 4. Remove Session Directories ---
SESSION_DIR="$WORKSPACE_ROOT/sessions/$GUID/$ENV"
if [[ -d "$SESSION_DIR" ]]; then
    echo "Removing Session Directory: $SESSION_DIR"
    rm -rf "$SESSION_DIR"
fi

# --- 5. Remove USoT Config (Last Step) ---
echo "Removing USoT Config: $CONFIG_PATH"
rm -f "$CONFIG_PATH"

echo "=== UNINSTALLATION COMPLETE ==="
echo "Client $GUID has been fully ejected and removed."